        public static string Translate(string? text)
        {
            if (string.IsNullOrWhiteSpace(text)) return text ?? string.Empty;
            string trimmed = text.Trim();
            if (Dictionary.TryGetValue(trimmed, out var exact)) return exact;

            if (trimmed.Contains('>') || trimmed.Contains('/'))
            {
                var parts = trimmed.Split(new[] { '>', '/' }, StringSplitOptions.None);
                for (int i = 0; i < parts.Length; i++)
                {
                    string p = parts[i].Trim();
                    if (Dictionary.TryGetValue(p, out var t))
                        parts[i] = t;
                }
                return string.Join(" > ", parts.Select(p => p.Trim()));
            }

            return trimmed;
        }

        public static string ExtractCategoryNameFromUrl(string? url)
        {
            if (string.IsNullOrWhiteSpace(url)) return string.Empty;
            try
            {
                string raw = url.Trim();
                int catIdx = raw.IndexOf("-cat.", StringComparison.OrdinalIgnoreCase);
                if (catIdx > 0)
                {
                    int lastSlash = raw.LastIndexOf('/', catIdx);
                    string slug = lastSlash >= 0 ? raw.Substring(lastSlash + 1, catIdx - lastSlash - 1) : raw.Substring(0, catIdx);
                    slug = slug.Trim();
                    if (Dictionary.TryGetValue(slug, out var direct)) return direct;
                    string slugWithSpaces = slug.Replace("-", " ");
                    if (Dictionary.TryGetValue(slugWithSpaces, out var spaceDirect)) return spaceDirect;
                    return slugWithSpaces;
                }
            }
            catch { }
            return string.Empty;
        }
